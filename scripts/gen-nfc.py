"""Writes llm/src/main/scala/mlx/llm/NfcTables.scala from Python's unicodedata: canonical decompositions (full),
canonical combining classes, and the primary composites. `python3 scripts/gen-nfc.py`"""
import sys, unicodedata as u

def canon(c):
    d = u.decomposition(chr(c))
    if not d or d.startswith('<'): return None
    return [int(x, 16) for x in d.split()]

def full(c):
    d = canon(c)
    if d is None: return [c]
    out = []
    for x in d: out += full(x)
    return out

decomp, ccc, comp = [], [], []
for c in range(0x110000):
    if 0xAC00 <= c <= 0xD7A3: continue               # Hangul: by formula
    k = u.combining(chr(c))
    if k: ccc += [c, k]
    d = canon(c)
    if d is not None:
        decomp.append((c, full(c)))
        if len(d) == 2 and u.normalize('NFC', chr(d[0]) + chr(d[1])) == chr(c):
            comp += [d[0], d[1], c]

def chunks(xs, per=20):
    """the numbers in base 36, `per` to a string literal: lines within 120 characters"""
    def b36(n):
        d = '0123456789abcdefghijklmnopqrstuvwxyz'; s = ''
        while True:
            s = d[n % 36] + s; n //= 36
            if n == 0: return s
    parts = [' '.join(b36(x) for x in xs[i:i + per]) for i in range(0, len(xs), per)]
    return ',\n    '.join('"' + p + '"' for p in parts)

flat = []
for c, d in decomp: flat += [c, len(d)] + d
src = f'''package mlx.llm

// GENERATED by scripts/gen-nfc.py from Python's unicodedata (Unicode {u.unidata_version}) — do not edit

/** Unicode's canonical data, numbers in base 36: full decompositions (a code point, the length, the code points),
 * combining classes (pairs), primary composites (triples: first, second, composed) */
private[llm] object NfcTables:
  private def read(parts: String*): Array[Int] =
    parts.iterator.flatMap(_.split(' ')).map(Integer.parseInt(_, 36)).toArray
  lazy val decompositions: Array[Int] = read(
    {chunks(flat)})
  lazy val combiningClasses: Array[Int] = read(
    {chunks(ccc)})
  lazy val composites: Array[Int] = read(
    {chunks(comp)})
'''
open('llm/src/main/scala/mlx/llm/NfcTables.scala', 'w').write(src)
print(len(decomp), len(ccc) // 2, len(comp) // 3, u.unidata_version)
